# 1. 有一行日志
日志 = "2026-9-27 INFO 用户登录成功"  # INFO指information是正常信息表示级别

# 2. 用空格把它切开 （空格也可以当刀)
# split（）默认就是按空格切
切好的段落 = 日志.split()

# 3. 切完变成一个列表,我们把里面的东西拿出来
日期 = 切好的段落[0]  # 第一个东西(编号从0开始)
级别 = 切好的段落[1]  # 第二个东西
内容 = 切好的段落[2]  # 第三个东西

# 4. 打印出来看看
print("日期是:", 日期)
print("级别是:", 级别)
print("内容是:", 内容)