# 1. 用set去重
全部报名 = ["张三", "李四", "张三", "王五", "李四"]
去重后 = set(全部报名) # set() 就是去重工具
print(f"去重后的名单：{去重后}")

# 2. 交集并集（找出两个集合的关系名单 = {"张三", "李四", "王五"}
男生名单 = {"张三", "李四", "王五"} # 补上对“男生名单”的定义
及格名单 = {"张三", "王五", "赵六"}

都及格的男生 = 男生名单 & 及格名单 # & 表示交集（都在）
print(f"既在男生名单又及格的：{都及格的男生}")

所有人 = 男生名单 | 及格名单 # | 表示并集（所有出现过的）
print(f"出现过的所有人：{所有人}")

# 3. 练习：名单找缺勤、统计实到率
应到 = {"张三", "李四", "王五", "赵六"}
实到 = {"张三", "王五"}

缺勤 = 应到 - 实到 # - 表示差集
实到率 = len(实到) / len(应到) * 100
print(f"缺勤的人：{缺勤}")
print(f"实到率：{实到率}%")