import random # 导入随机数工具

# 1. 电脑随机生成一个 1 到 100 之间的整数
正确答案 = random.randint(1, 100)
次数 = 0 # 计数器，初始为 0

print("欢迎来到猜数字游戏！我心里想了一个 1-100 的数字。")

# 2. 循环（死循环的诞生）
while True: # 当条件为真时，一直循环
    猜的数字 = int(input("请输入你猜的数字：")) # 用 int() 把输入的文本变成整数
    次数 = 次数 + 1 # 每猜一次，计数器加1
    
    # 3. 判断条件（控制流）
    if 猜的数字 > 正确答案:
        print("猜大了！")
    elif 猜的数字 < 正确答案:
        print("猜小了！")
    else:
        print(f"恭喜你，猜对了！你一共猜了 {次数} 次。")
        break # 猜对了，退出循环（如果没有这个break，就是死循环）