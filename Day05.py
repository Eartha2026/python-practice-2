# 1. 成绩列表
成绩 = [88,95,60,72,45,30,90]

# 2. 算出平均分(总分除以人数)
总分 = sum(成绩)  # sum是求和工具
人数 = len(成绩)  # len是数一数有几个工具
平均分 = 总分 / 人数
print("平均分:", 平均分)

# 3. 找最高分
最高分 = max(成绩)  # max是找最大值的工具
print("最高分:", 最高分)

# 4. 数不及格人数(这里要用到for遍历)
不及格个数 = 0  # 先准备一个计数器,初始是0
for 分数 in 成绩:  # 把抽屉里的分数挨个拿出来
    if 分数 < 60:  # 如果这个分数小于60
        不及格个数 = 不及格个数 + 1  # 计数器加一
        print("不及格人数:", 不及格个数)