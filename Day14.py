# Day14.py 类与实例
class Student: # 类名首字母要大写（英语习惯）
    def __init__(self, 姓名, 分数): # 构造函数，造物主
        self.姓名 = 姓名 # 绑定属性
        self.分数 = 分数
    
    def 打招呼(self): # 类里面的函数叫做“方法”
        print(f"大家好，我是{self.姓名}，我考了{self.分数}分。")

# 实例化（按图纸造出3个具体的人）
学生1 = Student("张三", 88)
学生2 = Student("李四", 45)
学生3 = Student("王五", 95)

学生1.打招呼() # 调用方法
学生2.打招呼()
学生3.打招呼()