# 1. 创建一个通讯录(字典)
通讯录 = {"张三": "13500000000", "李四": "13511111111"}

# 2. 查(用 get 安全取值,找不到不会报错)
查名字 = input("请输入你要查的名字: ")  # 让你自己输入
电话 = 通讯录.get(查名字, "查无此人")  # 如果找不到,默认给个"查无此人"
print("电话是:", 电话)

# 3. 增 / 改
通讯录["王五"] = "13522222222"  # 增加
通讯录["张三"] = "13533333333"  # 修改(因为张三已经在了,就会覆盖原来的)

# 4. 删
del 通讯录["李四"]  # 删掉李四

# 5. 用items()打印全部
print("\n--- 最新通讯录 ---")
for 名字, 电话 in 通讯录.items():  #items()把名字和电话成对拿出来
    print(f"名字: {名字}, 电话: {电话}")