# 定义第一个函数：算平均分
def 算平均分(成绩列表): # 参数是成绩列表
    总分 = sum(成绩列表)
    平均分 = 总分 / len(成绩列表)
    return 平均分 # 返回计算结果

# 定义第二个函数：数不及格人数
def 数不及格(成绩列表):
    不及格名单 = [] # 局部变量，只在这个函数里面活着
    for 分数 in 成绩列表:
        if 分数 < 60:
            不及格名单.append(分数)
    return 不及格名单 # 返回一个列表

# 定义第三个函数：打印总结报告
def 打印报告(成绩列表):
    avg = 算平均分(成绩列表) # 调用第一个函数
    不及格 = 数不及格(成绩列表) # 调用第二个函数
    print(f"平均分是：{avg}")
    print(f"不及格名单：{不及格}")

# 主程序（真正的起点）
我的成绩 = [88, 95, 60, 72, 45, 30, 90]
打印报告(我的成绩) # 调用函数跑起来