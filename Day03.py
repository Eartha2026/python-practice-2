num1 = float(input("请输入第一个数字:"))
print(num1)
num2 = float(input("请输入第二个数字:"))  # 把数字存进盒子里
print(num2)
jia = num1 + num2 
jian = num1 - num2
cheng = num1 * num2
chu = num1 / num2
