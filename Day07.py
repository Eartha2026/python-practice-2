# 1. 建档案：列表套字典（list 套 dict）
# 列表用 []，字典用 {} 。 每个字典就是一张学生档案。
学生名单 = [
    {"姓名": "张三", "分数": 88},
    {"姓名": "李四", "分数": 45},
    {"姓名": "王五", "分数": 95},
    {"姓名": "赵六", "分数": 58},
    {"姓名": "孙七", "分数": 72}
]

# 2. 查询：输入名字，查找分数
查名字 = input("请输入你要查询的学生名字：") # 让你键盘输入
找到了 = False # 先假设找不到
for 学生 in 学生名单: # 遍历列表中的每一个字典
    if 学生["姓名"] == 查名字: # 如果字典里的“姓名”等于你输入的
        print(f"找到啦！{学生['姓名']}的分数是：{学生['分数']}")
        找到了 = True
        break # 找到就跳出循环，不用再找了

if 找到了 == False:
    print("查无此人！")

# 3. 添加：把新同学加进列表
新同学 = {"姓名": "周八", "分数": 80}
学生名单.append(新同学) # append() 就是把新东西塞到列表末尾
print(f"添加了周八，现在总共有 {len(学生名单)} 个学生。")

# 4. 按条件统计：计算平均分、找不及格名单
总分 = 0
不及格名单 = [] # 准备一个空列表装名字

for 学生 in 学生名单: # 遍历每一个学生字典
    总分 = 总分 + 学生["分数"] # 把分数累加
    
    if 学生["分数"] < 60: # 按条件筛选
        不及格名单.append(学生["姓名"]) # 把不及格的名字塞进列表

平均分 = 总分 / len(学生名单) # 总分除以人数
print(f"全班平均分：{平均分}")
print(f"不及格名单：{不及格名单}")